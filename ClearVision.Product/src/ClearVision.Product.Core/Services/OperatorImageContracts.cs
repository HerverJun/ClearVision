        OperatorType operatorType,
        IReadOnlyList<string> imageInputPorts,
        OperatorLifecycle lifecycle);
}

/// <summary>
/// Resolves image contracts from the same provider for scanner and runtime use.
/// Operators without a dedicated provider receive a conservative Stage 2 contract:
/// legacy 8U execution remains available, while higher depths are rejected until
/// operator-specific evidence promotes them.
/// </summary>
public static class OperatorImageContractResolver
{
    public const string ContractVersion = "2.1";

    private static readonly string[] StandardDepths =
        ["CV_8U", "CV_8S", "CV_16U", "CV_16S", "CV_32S", "CV_32F", "CV_64F"];

    public static IReadOnlyList<ImageInputContract> Resolve(
        Type operatorClrType,
        OperatorType operatorType)
    {
        ArgumentNullException.ThrowIfNull(operatorClrType);

        var imagePorts = operatorClrType
            .GetCustomAttributes<InputPortAttribute>(inherit: false)
            .Where(attribute => attribute.DataType == PortDataType.Image)
            .Select(attribute => attribute.Name)
            .Where(name => !string.IsNullOrWhiteSpace(name))
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        if (imagePorts.Length == 0)
        {
            return [];
        }

        var lifecycle = operatorClrType
            .GetCustomAttribute<OperatorMetaAttribute>(inherit: false)?
            .Lifecycle ?? OperatorLifecycle.Stable;
        var providerAttribute = operatorClrType
            .GetCustomAttribute<OperatorImageContractProviderAttribute>(inherit: false);
        if (providerAttribute is not null)
        {
            if (!typeof(IOperatorImageContractProvider).IsAssignableFrom(providerAttribute.ProviderType))
            {
                throw new InvalidOperationException(
                    $"Image contract provider '{providerAttribute.ProviderType.FullName}' for '{operatorClrType.FullName}' " +
                    $"must implement {nameof(IOperatorImageContractProvider)}.");
            }

            if (Activator.CreateInstance(providerAttribute.ProviderType) is not IOperatorImageContractProvider provider)
            {
                throw new InvalidOperationException(
                    $"Image contract provider '{providerAttribute.ProviderType.FullName}' could not be created.");
            }

            var resolved = provider.GetContracts(operatorType, imagePorts, lifecycle)
                .Where(contract => contract is not null)
                .ToArray();
            ValidateResolvedContracts(operatorClrType, imagePorts, resolved);
            return resolved;
        }

        var defaults = imagePorts
            .Select(port => CreateConservativeDefault(port, lifecycle))
            .ToArray();
        ValidateResolvedContracts(operatorClrType, imagePorts, defaults);
        return defaults;
    }

    public static ImageInputContract CreateConservativeDefault(
        string inputPort,
        OperatorLifecycle lifecycle)
    {
        var isExperimental = lifecycle == OperatorLifecycle.Experimental;
        var variants = CreateConservativeDefaultVariants(isExperimental);
        return new ImageInputContract(
            inputPort,
            isExperimental ? [] : ["CV_8U"],
            isExperimental ? [] : [1, 3, 4],
            isExperimental ? [] : ["CV_8U"],
            isExperimental
                ? "Unverified image depth domain; Unknown is not support."
                : "Legacy 8U compatibility allowance — unverified. Higher-depth and undeclared combinations remain Unknown and fail closed.",
            "None",
            "Operator-specific legacy output policy; no Stage 2 depth widening.",
            isExperimental
                ? "Undefined until verified."
                : "8-bit native numeric domain; no implicit MinMax conversion.",
            variants,
            isExperimental ? "Unknown" : "NotApplicableFor8U",
            "IMAGE_DEPTH_UNSUPPORTED",
            ContractVersion);
    }

    private static IReadOnlyList<ImageContractVariant> CreateConservativeDefaultVariants(bool isExperimental)
    {
        var variants = new List<ImageContractVariant>();
        foreach (var depth in StandardDepths)
        {
            foreach (var channels in new[] { 1, 2, 3, 4 })
            {
                var isLegacyAllowance = !isExperimental &&
                                        depth == "CV_8U" &&
                                        channels is 1 or 3 or 4;
                variants.Add(new ImageContractVariant(
                    "Default",
                    depth,
                    channels,
                    isLegacyAllowance
                        ? "Legacy 8U execution path retained for compatibility; no per-operator E2 evidence."
                        : "No operator-specific executable evidence is registered.",
                    isLegacyAllowance ? ImageContractAdmission.Allowed : ImageContractAdmission.Unknown,
                    isLegacyAllowance
                        ? ImageContractVerification.LegacyCompatibilityAllowance
                        : ImageContractVerification.Unknown,
                    "None",
                    "Operator-specific legacy output policy; no Stage 2 depth widening.",
                    isLegacyAllowance ? "8-bit legacy numeric domain." : "Undefined until verified.",
                    ImageContractInputValuePolicy.Any,
                    isLegacyAllowance ? "IMAGE_DEPTH_UNSUPPORTED" : "IMAGE_CONTRACT_UNKNOWN",
                    isLegacyAllowance ? "E0_SOURCE_AUDIT" : "Unknown"));
            }
        }

        return variants;
    }

    private static void ValidateResolvedContracts(
        Type operatorClrType,
        IReadOnlyList<string> imagePorts,
        IReadOnlyList<ImageInputContract> contracts)
    {
        var declaredPorts = imagePorts.ToHashSet(StringComparer.Ordinal);
        var contractPorts = contracts.Select(contract => contract.InputPort).ToList();
        contractPorts.ShouldContainEachDeclaredPort(operatorClrType, declaredPorts);

        foreach (var contract in contracts)
        {
            if (!declaredPorts.Contains(contract.InputPort))
            {
                throw new InvalidOperationException(
                    $"Image contract for '{operatorClrType.FullName}' references undeclared input port '{contract.InputPort}'.");
            }

            if (string.IsNullOrWhiteSpace(contract.ContractVersion) ||
                string.IsNullOrWhiteSpace(contract.FailureCode) ||
                contract.Variants.Count == 0)
            {
                throw new InvalidOperationException(
                    $"Image contract for '{operatorClrType.FullName}:{contract.InputPort}' is incomplete.");
            }

            ValidateVariants(operatorClrType, contract);
        }
    }

    private static void ValidateVariants(Type operatorClrType, ImageInputContract contract)
    {
        var duplicate = contract.Variants
            .GroupBy(variant => (variant.Mode, variant.Depth, variant.Channels))
            .FirstOrDefault(group => group.Count() > 1);
        if (duplicate is not null)
        {
            throw new InvalidOperationException(
                $"Image contract for '{operatorClrType.FullName}:{contract.InputPort}' contains duplicate exact variant " +
                $"Mode={duplicate.Key.Mode}, Depth={duplicate.Key.Depth}, Channels={duplicate.Key.Channels}.");
        }

        foreach (var variant in contract.Variants)
        {
            if (string.IsNullOrWhiteSpace(variant.Mode) ||
                string.IsNullOrWhiteSpace(variant.Depth) ||
                variant.Channels <= 0 ||
                string.IsNullOrWhiteSpace(variant.Condition) ||
                string.IsNullOrWhiteSpace(variant.FailureCode) ||
                string.IsNullOrWhiteSpace(variant.EvidenceLevel))
            {
                throw new InvalidOperationException(
                    $"Image contract variant for '{operatorClrType.FullName}:{contract.InputPort}' is incomplete.");
            }

            var verificationMatchesAdmission = variant.Admission switch
            {
                ImageContractAdmission.Allowed => variant.Verification is
                    ImageContractVerification.VerifiedSupport or
                    ImageContractVerification.VerifiedConversion or
                    ImageContractVerification.LegacyCompatibilityAllowance,
                ImageContractAdmission.Rejected =>
                    variant.Verification == ImageContractVerification.VerifiedRejection,
                ImageContractAdmission.Unknown =>
                    variant.Verification == ImageContractVerification.Unknown,
                _ => false
            };
            if (!verificationMatchesAdmission)
            {
                throw new InvalidOperationException(
                    $"Image contract variant for '{operatorClrType.FullName}:{contract.InputPort}' has inconsistent " +
                    $"Admission={variant.Admission} and Verification={variant.Verification}.");
            }

            if (variant.EvidenceLevel.StartsWith("E0", StringComparison.OrdinalIgnoreCase) &&
                variant.Verification != ImageContractVerification.LegacyCompatibilityAllowance)
            {
                throw new InvalidOperationException(
                    $"E0 image evidence for '{operatorClrType.FullName}:{contract.InputPort}' may only describe an unverified legacy compatibility allowance.");
            }
        }

        var allowed = contract.Variants
            .Where(variant => variant.Admission == ImageContractAdmission.Allowed)
            .ToArray();
        var summaryDepths = allowed.Select(variant => variant.Depth)
            .Distinct(StringComparer.Ordinal)
            .OrderBy(value => value, StringComparer.Ordinal)
            .ToArray();
        var summaryChannels = allowed.Select(variant => variant.Channels)
            .Distinct()
            .OrderBy(value => value)
            .ToArray();
        if (!summaryDepths.SequenceEqual(contract.SupportedDepths.OrderBy(value => value, StringComparer.Ordinal), StringComparer.Ordinal) ||
            !summaryChannels.SequenceEqual(contract.SupportedChannels.OrderBy(value => value)))
        {
            throw new InvalidOperationException(
                $"Image contract summaries for '{operatorClrType.FullName}:{contract.InputPort}' do not match its allowed exact variants.");
        }
    }

    private static void ShouldContainEachDeclaredPort(
        this IReadOnlyCollection<string> contractPorts,
        Type operatorClrType,
        IReadOnlySet<string> declaredPorts)
    {
        foreach (var port in declaredPorts)
        {
            if (!contractPorts.Contains(port, StringComparer.Ordinal))
            {
                throw new InvalidOperationException(
                    $"Image contract provider for '{operatorClrType.FullName}' did not describe input port '{port}'.");
            }
        }
    }
