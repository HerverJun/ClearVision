public static class ImageContractPresentationBuilder
{
    public const string LegacyCompatibilityNotice = "Legacy 8U compatibility allowance — unverified";

    public static ImageInputContractPresentation Build(ImageInputContract contract)
    {
        ArgumentNullException.ThrowIfNull(contract);

        var variants = contract.Variants ?? [];
        var verifiedSupport = variants.Count(item => item.Verification == ImageContractVerification.VerifiedSupport);
        var verifiedConversion = variants.Count(item => item.Verification == ImageContractVerification.VerifiedConversion);
        var compatibility = variants.Count(item => item.Verification == ImageContractVerification.LegacyCompatibilityAllowance);
        var verifiedRejection = variants.Count(item => item.Verification == ImageContractVerification.VerifiedRejection);
        var unknown = variants.Count(item => item.Verification == ImageContractVerification.Unknown);
        var allowed = variants.Count(item => item.Admission == ImageContractAdmission.Allowed);
        var hasProductionSupport = verifiedSupport + verifiedConversion > 0;
        var compatibilityOnly = compatibility > 0 && !hasProductionSupport;

        var groups = variants
            .GroupBy(item => new
            {
                item.Mode,
                item.Condition,
                item.Admission,
                item.Verification,
                item.ConversionPolicy,
                item.OutputDepthPolicy,
                item.DynamicRangePolicy,
                item.InputValuePolicy,
                item.FailureCode,
                item.EvidenceLevel
            })
            .OrderBy(group => group.Key.Mode, StringComparer.Ordinal)
            .ThenBy(group => group.Key.Condition, StringComparer.Ordinal)
            .ThenBy(group => group.Key.Admission)
            .ThenBy(group => group.Key.Verification)
            .Select(group => new ImageContractVariantPresentation(
                group.Key.Mode,
                group.Key.Condition,
                group.Key.Admission,
                group.Key.Verification,
                group
                    .OrderBy(item => GetDepthOrder(item.Depth))
                    .ThenBy(item => item.Channels)
                    .Select(item => FormatInputType(item.Depth, item.Channels))
                    .Distinct(StringComparer.Ordinal)
                    .ToArray(),
                group.Key.ConversionPolicy,
                group.Key.OutputDepthPolicy,
                group.Key.DynamicRangePolicy,
                group.Key.InputValuePolicy,
                group.Key.FailureCode,
                group.Key.EvidenceLevel))
            .ToArray();

        return new ImageInputContractPresentation(
            contract.InputPort,
            contract.ContractVersion,
            allowed,
            verifiedSupport,
            verifiedConversion,
            compatibility,
            verifiedRejection,
            unknown,
            hasProductionSupport,
            compatibilityOnly,
            BuildEvidenceSummary(hasProductionSupport, compatibilityOnly, compatibility, unknown),
            groups);
    }

    public static IReadOnlyList<ImageInputContractPresentation> Build(
        IEnumerable<ImageInputContract> contracts) =>
        contracts?.Select(Build).ToArray() ?? [];

    public static IReadOnlyList<ImageInputContractCompactPresentation> BuildCompact(
        IEnumerable<ImageInputContract> contracts) =>
        Build(contracts).Select(BuildCompact).ToArray();

    public static IReadOnlyList<ImageInputContractModeIndex> BuildModeIndex(
        IEnumerable<ImageInputContract> contracts) =>
        Build(contracts).Select(BuildModeIndex).ToArray();

    public static IReadOnlyList<ImageInputContractModeIndex> BuildModeIndex(
        IEnumerable<ImageInputContractPresentation> presentations) =>
        presentations?.Select(BuildModeIndex).ToArray() ?? [];

    public static IReadOnlyList<ImageInputContractCompactPresentation> BuildModeDetails(
        IEnumerable<ImageInputContract> contracts,
        string mode)
    {
        if (string.IsNullOrWhiteSpace(mode))
        {
            return BuildCompact(contracts);
        }

        return BuildCompact(contracts)
            .Select(contract => contract with
            {
                Variants = contract.Variants
                    .Where(group => group.Modes.Contains(mode, StringComparer.OrdinalIgnoreCase))
                    .Select(group => group with
                    {
                        Modes = group.Modes
                            .Where(value => value.Equals(mode, StringComparison.OrdinalIgnoreCase))
                            .ToArray()
                    })
                    .ToArray()
            })
            .Where(contract => contract.Variants.Count > 0)
            .ToArray();
    }

    public static ImageInputContractModeIndex BuildModeIndex(
        ImageInputContractPresentation presentation)
    {
        ArgumentNullException.ThrowIfNull(presentation);

        var casesByMode = presentation.ExactVariantGroups
            .GroupBy(group => group.Mode, StringComparer.Ordinal)
            .ToDictionary(
                group => group.Key,
                group => group
                    .Select(item => new ImageContractModeCase(
                        item.ExactInputTypes,
                        item.Admission,
                        item.Verification,
                        item.FailureCode,
                        item.EvidenceLevel))
                    .OrderBy(item => item.Admission)
                    .ThenBy(item => item.Verification)
                    .ThenBy(item => string.Join('\u001F', item.Inputs), StringComparer.Ordinal)
                    .ToArray(),
                StringComparer.Ordinal);

        var modeGroups = casesByMode
            .GroupBy(item => JsonSerializer.Serialize(item.Value))
            .OrderBy(group => group.Min(item => item.Key), StringComparer.Ordinal)
            .Select(group => new ImageContractModeGroup(
                group.Select(item => item.Key)
                    .OrderBy(value => value, StringComparer.Ordinal)
                    .ToArray(),
                group.First().Value))
            .ToArray();

        return new ImageInputContractModeIndex(
            presentation.InputPort,
            presentation.ContractVersion,
            presentation.EvidenceSummary,
            modeGroups);
    }

    public static ImageInputContractCompactPresentation BuildCompact(
        ImageInputContractPresentation presentation)
    {
        ArgumentNullException.ThrowIfNull(presentation);

        var groups = presentation.ExactVariantGroups
            .GroupBy(item => new
            {
                Inputs = string.Join('\u001F', item.ExactInputTypes),
                item.Condition,
                item.Admission,
                item.Verification,
                item.ConversionPolicy,
                item.OutputDepthPolicy,
                item.DynamicRangePolicy,
                item.InputValuePolicy,
                item.FailureCode,
                item.EvidenceLevel
            })
            .OrderBy(group => group.Min(item => item.Mode), StringComparer.Ordinal)
            .ThenBy(group => group.Key.Inputs, StringComparer.Ordinal)
            .Select(group => new ImageContractCompactVariantGroup(
                group.Select(item => item.Mode)
                    .Distinct(StringComparer.Ordinal)
                    .OrderBy(value => value, StringComparer.Ordinal)
                    .ToArray(),
                group.First().ExactInputTypes,
                group.Key.Condition,
                group.Key.Admission,
                group.Key.Verification,
                group.Key.ConversionPolicy,
                group.Key.OutputDepthPolicy,
                group.Key.DynamicRangePolicy,
                group.Key.InputValuePolicy,
                group.Key.FailureCode,
                group.Key.EvidenceLevel))
            .ToArray();

        return new ImageInputContractCompactPresentation(
            presentation.InputPort,
            presentation.ContractVersion,
            presentation.EvidenceSummary,
            presentation.VerifiedSupportVariantCount,
            presentation.VerifiedConversionVariantCount,
            presentation.LegacyCompatibilityVariantCount,
            presentation.VerifiedRejectionVariantCount,
            presentation.UnknownVariantCount,
            groups);
    }

    public static OperatorImageContractPresentationSummary Summarize(
        IEnumerable<ImageInputContract> contracts)
    {
        var presentations = Build(contracts);
        var verifiedSupport = presentations.Sum(item => item.VerifiedSupportVariantCount);
        var verifiedConversion = presentations.Sum(item => item.VerifiedConversionVariantCount);
        var compatibility = presentations.Sum(item => item.LegacyCompatibilityVariantCount);
        var unknown = presentations.Sum(item => item.UnknownVariantCount);
        var hasProductionSupport = verifiedSupport + verifiedConversion > 0;
        var compatibilityOnly = compatibility > 0 && !hasProductionSupport;

        return new OperatorImageContractPresentationSummary(
            presentations.Count,
            presentations.Sum(item => item.AllowedVariantCount),
            verifiedSupport,
            verifiedConversion,
            compatibility,
            presentations.Sum(item => item.VerifiedRejectionVariantCount),
            unknown,
            hasProductionSupport,
            compatibilityOnly,
            BuildEvidenceSummary(hasProductionSupport, compatibilityOnly, compatibility, unknown));
    }

    public static bool IsDefaultAiRecommendation(
        OperatorLifecycle lifecycle,
        IEnumerable<ImageInputContract> contracts)
    {
        if (!OperatorLifecyclePolicy.IsDefaultAiRecommendation(lifecycle))
        {
            return false;
        }

        var summary = Summarize(contracts);
        return summary.ContractCount == 0 || summary.HasProductionSupport;
    }

    public static bool RequiresAiDisclosure(
        OperatorLifecycle lifecycle,
        IEnumerable<ImageInputContract> contracts)
    {
        if (OperatorLifecyclePolicy.RequiresDisclosure(lifecycle))
        {
            return true;
        }

        var summary = Summarize(contracts);
        return summary.ContractCount > 0 &&
               (summary.LegacyCompatibilityVariantCount > 0 ||
                summary.UnknownVariantCount > 0 ||
                !summary.HasProductionSupport);
    }

    public static string FormatInputType(string depth, int channels) => $"{depth}C{channels}";

    private static string BuildEvidenceSummary(
        bool hasProductionSupport,
        bool compatibilityOnly,
        int compatibilityCount,
        int unknownCount)
    {
        if (compatibilityOnly)
        {
            return LegacyCompatibilityNotice;
        }

        if (hasProductionSupport && compatibilityCount > 0)
        {
            return $"Verified production support is present; {LegacyCompatibilityNotice}.";
        }

        if (hasProductionSupport)
        {
            return "Verified production support is present.";
        }

        return unknownCount > 0
            ? "Unknown — no verified executable image support is registered."
            : "No executable image support is admitted.";
    }

    private static int GetDepthOrder(string depth) => depth switch
    {
        "CV_8U" => 0,
        "CV_8S" => 1,
        "CV_16U" => 2,
        "CV_16S" => 3,
        "CV_32S" => 4,
        "CV_32F" => 5,
        "CV_64F" => 6,
        _ => int.MaxValue
    };
}

#pragma warning disable CS0618
internal static class ImageContractCompatibilityAdapter
{
    public static IReadOnlyList<ImageContractVariant> ToExactVariants(
        IReadOnlyList<string> supportedDepths,
        IReadOnlyList<int> supportedChannels,
        IReadOnlyList<ImageModeRestriction> modeRestrictions,
        ImageContractStatus status,
        string conversionPolicy,
        string outputDepthPolicy,
        string dynamicRangePolicy,
        string failureCode,
        string evidenceLevel)
    {
        var restrictions = modeRestrictions is { Count: > 0 }
            ? modeRestrictions
            :
            [
                new ImageModeRestriction(
                    "Default",
                    status,
                    supportedDepths,
                    supportedChannels,
                    conversionPolicy,
                    outputDepthPolicy,
                    dynamicRangePolicy,
                    failureCode,
                    evidenceLevel,
                    "Legacy compatibility contract")
            ];

        return restrictions
            .SelectMany(rule => rule.SupportedDepths.SelectMany(depth =>
                rule.SupportedChannels.Select(channels =>
                {
                    var (admission, verification) = Map(rule.Status, rule.EvidenceLevel);
                    return new ImageContractVariant(
                        rule.Mode,
                        depth,
                        channels,
                        string.IsNullOrWhiteSpace(rule.Condition) ? "Legacy compatibility contract" : rule.Condition,
                        admission,
                        verification,
                        rule.ConversionPolicy,
                        rule.OutputDepthPolicy,
                        rule.DynamicRangePolicy,
                        ImageContractInputValuePolicy.Any,
                        rule.FailureCode,
                        rule.EvidenceLevel);
                })))
            .ToArray();
    }

    public static ImageContractStatus GetLegacyStatus(IReadOnlyList<ImageContractVariant> variants)
    {
        if (variants.Any(item => item.Verification == ImageContractVerification.VerifiedConversion))
            return ImageContractStatus.Converted;
        if (variants.Any(item => item.Verification == ImageContractVerification.VerifiedSupport))
            return ImageContractStatus.Native;
        if (variants.Any(item => item.Verification == ImageContractVerification.LegacyCompatibilityAllowance))
            return ImageContractStatus.Restricted;
        if (variants.Count > 0 && variants.All(item => item.Admission == ImageContractAdmission.Rejected))
            return ImageContractStatus.Rejected;
        return ImageContractStatus.Unknown;
    }

    public static IReadOnlyList<ImageModeRestriction> GetLegacyRestrictions(
        IReadOnlyList<ImageContractVariant> variants) =>
        variants.Select(item => new ImageModeRestriction(
            item.Mode,
            GetLegacyStatus([item]),
            [item.Depth],
            [item.Channels],
            item.ConversionPolicy,
            item.OutputDepthPolicy,
            item.DynamicRangePolicy,
            item.FailureCode,
            item.EvidenceLevel,
            item.Condition)).ToArray();

    public static string GetLegacyEvidenceLevel(IReadOnlyList<ImageContractVariant> variants)
    {
        var levels = variants.Select(item => item.EvidenceLevel)
            .Distinct(StringComparer.Ordinal)
            .ToArray();
        return levels.Length == 1 ? levels[0] : "Mixed";
    }

    private static (ImageContractAdmission Admission, ImageContractVerification Verification) Map(
        ImageContractStatus status,
        string evidenceLevel) => status switch
    {
        ImageContractStatus.Native =>
            (ImageContractAdmission.Allowed, ImageContractVerification.VerifiedSupport),
        ImageContractStatus.Converted =>
            (ImageContractAdmission.Allowed, ImageContractVerification.VerifiedConversion),
        ImageContractStatus.Restricted when evidenceLevel.StartsWith("E0", StringComparison.OrdinalIgnoreCase) =>
            (ImageContractAdmission.Allowed, ImageContractVerification.LegacyCompatibilityAllowance),
        ImageContractStatus.Rejected =>
            (ImageContractAdmission.Rejected, ImageContractVerification.VerifiedRejection),
        _ => (ImageContractAdmission.Unknown, ImageContractVerification.Unknown)
    };
}
